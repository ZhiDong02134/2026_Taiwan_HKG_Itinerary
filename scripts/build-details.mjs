// Builds assets/details.js from the verified per-stop research in data/details/*.json.
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'data', 'details');
const TEXT_FIELDS = ['hours', 'cost', 'getThere', 'watch'];
const LIST_FIELDS = ['highlights', 'tips'];
const out = {};
let itemCount = 0;
const urls = new Set();

for (const file of readdirSync(dir).filter(name => /^day-\d{2}\.json$/.test(name)).sort()) {
  const data = JSON.parse(readFileSync(path.join(dir, file), 'utf8'));
  assert.equal(`${data.day}.json`, file, `${file}: day id must match file name`);
  assert.match(data.checked, /^\d{4}-\d{2}-\d{2}$/, `${file}: checked date`);
  const items = {};
  for (const item of data.items) {
    const where = `${file} #${item.index}`;
    assert.ok(Number.isInteger(item.index) && item.index >= 0, `${where}: index`);
    assert.ok(!items[item.index], `${where}: duplicate index`);
    assert.ok(typeof item.title === 'string' && item.title, `${where}: title`);
    const clean = { title: item.title };
    for (const key of TEXT_FIELDS) {
      if (item[key] == null) continue;
      assert.equal(typeof item[key], 'string', `${where}: ${key}`);
      clean[key] = item[key].trim();
    }
    for (const key of LIST_FIELDS) {
      if (item[key] == null) continue;
      assert.ok(Array.isArray(item[key]) && item[key].every(entry => typeof entry === 'string'), `${where}: ${key}`);
      clean[key] = item[key].map(entry => entry.trim()).filter(Boolean);
    }
    assert.ok(Array.isArray(item.sources) && item.sources.length, `${where}: sources required`);
    clean.sources = item.sources.map(source => {
      const url = new URL(source.url);
      assert.ok(url.protocol === 'https:' || url.protocol === 'http:', `${where}: source protocol`);
      urls.add(url.href);
      return { label: String(source.label || url.hostname).trim(), url: url.href };
    });
    items[item.index] = clean;
    itemCount += 1;
  }
  out[data.day] = { checked: data.checked, items };
}

// Coordinates for the day map: data/coords.json, geocoded once (no runtime geocoding).
const coordsPath = path.join(root, 'data', 'coords.json');
const coords = JSON.parse(readFileSync(coordsPath, 'utf8'));
const inBox = ([lat, lng], [s, n, w, e]) => lat >= s && lat <= n && lng >= w && lng <= e;
const boxes = { tw: [21.8, 25.4, 119.9, 122.1], hk: [22.15, 22.6, 113.8, 114.45], ny: [40.4, 41.0, -74.3, -73.5] };
const compact = { hotels: {}, stops: {} };
for (const [key, value] of Object.entries(coords.hotels)) {
  assert.ok(Object.values(boxes).some(box => inBox([value.lat, value.lng], box)), `hotel ${key}: coordinates outside every region`);
  compact.hotels[key] = [value.lat, value.lng];
}
let coordCount = 0;
for (const [dayId, stops] of Object.entries(coords.stops)) {
  compact.stops[dayId] = {};
  for (const [index, value] of Object.entries(stops)) {
    assert.ok(Object.values(boxes).some(box => inBox([value.lat, value.lng], box)), `${dayId}#${index}: coordinates outside every region`);
    compact.stops[dayId][index] = [value.lat, value.lng, value.title];
    coordCount += 1;
  }
}

const body = `/* Generated by scripts/build-details.mjs from data/details/*.json and data/coords.json — edit the JSON, not this file. */\nwindow.TWHK_DETAILS = ${JSON.stringify(out)};\nwindow.TWHK_COORDS = ${JSON.stringify(compact)};\n`;
writeFileSync(path.join(root, 'assets', 'details.js'), body);
console.log(`details.js: ${Object.keys(out).length} days, ${itemCount} stops, ${urls.size} distinct sources, ${coordCount} coordinates, ${(body.length / 1024).toFixed(1)} KB`);
